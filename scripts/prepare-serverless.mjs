import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = resolve(projectRoot, '.env');
const configPath = resolve(projectRoot, 'tgcloud/lib/config.js');

function parseEnv(contents) {
  const values = {};

  for (const line of contents.split(/\r?\n/)) {
    const match = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!match || match[1].startsWith('#')) continue;

    let value = match[2];
    if (
      value.length >= 2 &&
      ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'")))
    ) {
      value = value.slice(1, -1);
    }

    values[match[1]] = value;
  }

  return values;
}

let env;
try {
  env = parseEnv(await readFile(envPath, 'utf8'));
} catch (error) {
  throw new Error(`Tidak dapat membaca ${envPath}: ${error.message}`);
}

const authHeader = env.BANGHASAN_AUTH_HEADER;
if (!authHeader) {
  throw new Error('BANGHASAN_AUTH_HEADER belum diatur di file .env');
}

await mkdir(dirname(configPath), { recursive: true });
await writeFile(
  configPath,
  `// Generated by scripts/prepare-serverless.mjs. Do not commit this file.\n` +
    `export const BANGHASAN_AUTH_HEADER = ${JSON.stringify(authHeader)};\n`,
  'utf8',
);

console.log('Serverless configuration prepared.');
